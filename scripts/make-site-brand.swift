// Writes the site's brand files from the app's own shapes, so the site never hand-copies the logo. `make site-brand`
// compiles this with Sources/AnnotakeApp/BrandMark.swift and Wordmark.swift, runs it as `make-site-brand <site/assets>`,
// and then adds img/favicon-32.png from the app icon. It writes:
//   brand.js                 the brand's colors, the tripod's numbers, and SVG path data, for the footer animation
//   img/brand.svg            a sprite with the logo and the mark, for <use>
//   img/favicon.svg          the mark on the app icon's charcoal body
//   img/apple-touch-icon.png the mark on a full-bleed charcoal square, since iOS rounds the corners itself and would
//                            fill the app icon's transparent margin with black
// `make site-brand-check` writes the text files to another folder and compares them with the committed ones.
import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

@main
struct MakeSiteBrand {
    static let header =
        "Generated by scripts/make-site-brand.swift from BrandMark.swift and Wordmark.swift. Don't edit: run make site-brand."
    /// Space around the logo and the mark in their view boxes, in logo units.
    static let padding: CGFloat = 6

    static func main() {
        guard CommandLine.arguments.count == 2 else {
            FileHandle.standardError.write(Data("usage: make-site-brand <assets folder>\n".utf8))
            exit(2)
        }
        let assets = URL(fileURLWithPath: CommandLine.arguments[1])
        do {
            try FileManager.default.createDirectory(at: assets.appending(path: "img"), withIntermediateDirectories: true)
            let brand = try Brand()
            try brand.script().write(to: assets.appending(path: "brand.js"), atomically: true, encoding: .utf8)
            try brand.sprite().write(to: assets.appending(path: "img/brand.svg"), atomically: true, encoding: .utf8)
            try brand.favicon().write(to: assets.appending(path: "img/favicon.svg"), atomically: true, encoding: .utf8)
            try writePNG(touchIcon(pixels: 180), to: assets.appending(path: "img/apple-touch-icon.png"))
            print("wrote brand.js, img/brand.svg, img/favicon.svg, and img/apple-touch-icon.png to \(assets.path)")
        } catch {
            FileHandle.standardError.write(Data("make-site-brand: \(error)\n".utf8))
            exit(1)
        }
    }

    /// The touch icon: the app icon's body, full-bleed, with the mark at the same share of its height.
    static func touchIcon(pixels: Int) -> CGImage {
        let size = CGFloat(pixels)
        let context = CGContext(data: nil, width: pixels, height: pixels, bitsPerComponent: 8, bytesPerRow: 0,
                                space: sRGB, bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
        context.translateBy(x: 0, y: size)
        context.scaleBy(x: 1, y: -1)
        let gradient = CGGradient(colorsSpace: sRGB, colors: [color(0x2C2C2E), color(0x1C1C1E)] as CFArray,
                                  locations: [0, 1])!
        context.drawLinearGradient(gradient, start: CGPoint(x: size / 2, y: 0), end: CGPoint(x: size / 2, y: size),
                                   options: [])
        let height = size * 0.62
        let width = height * BrandMark.bounds.width / BrandMark.bounds.height
        BrandMark.draw(in: context, rect: CGRect(x: (size - width) / 2, y: (size - height) / 2, width: width,
                                                 height: height),
                       ink: color(0xFFFFFF), frontReel: color(BrandMark.red))
        return context.makeImage()!
    }

    static let sRGB = CGColorSpace(name: CGColorSpace.sRGB)!

    static func color(_ hex: UInt32) -> CGColor {
        CGColor(colorSpace: sRGB, components: [CGFloat((hex >> 16) & 0xFF) / 255, CGFloat((hex >> 8) & 0xFF) / 255,
                                               CGFloat(hex & 0xFF) / 255, 1])!
    }

    static func writePNG(_ image: CGImage, to url: URL) throws {
        guard let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)
        else { throw Failure("can't write \(url.path)") }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { throw Failure("can't write \(url.path)") }
    }
}

struct Failure: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}

/// The brand, read from BrandMark and Wordmark.
struct Brand {
    /// BrandMark.shapes by name, in its order.
    static let names = ["leftLeg", "rightLeg", "brace", "body", "lens", "backReel", "frontReel"]

    let paths: [(name: String, data: String, evenOdd: Bool)]
    let letters: String
    let logoBox: CGRect
    let markBox: CGRect

    init() throws {
        let shapes = BrandMark.shapes
        guard shapes.count == Self.names.count, shapes.last?.part == .frontReel else {
            throw Failure("BrandMark.shapes has changed: expected \(Self.names.joined(separator: ", "))")
        }
        paths = zip(Self.names, shapes).map { ($0, pathData($1.path), $1.evenOdd) }
        letters = Wordmark.letterPaths.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        let pad = MakeSiteBrand.padding
        logoBox = try Wordmark.bounds().insetBy(dx: -pad, dy: -pad)
        let mark = BrandMark.bounds
        let side = max(mark.width, mark.height) + 2 * pad
        markBox = CGRect(x: mark.midX - side / 2, y: mark.midY - side / 2, width: side, height: side)
    }

    func path(_ name: String) -> String { paths.first { $0.name == name }!.data }

    func script() -> String {
        let geometry: [(String, CGFloat)] = [
            ("footSpan", BrandMark.footSpan), ("splayDegrees", BrandMark.splay * 180 / .pi), ("stem", BrandMark.stem),
            ("legThickness", BrandMark.legThickness), ("braceThickness", BrandMark.braceThickness),
            ("legTop", BrandMark.legTop), ("crossbarY", BrandMark.crossbarY),
        ]
        let reel = BrandMark.frontReelCenter
        let reelNumbers: [(String, CGFloat)] = [("cx", reel.x), ("cy", reel.y), ("outer", BrandMark.reelRadius),
                                                ("inner", BrandMark.reelHoleRadius)]
        func object(_ entries: [(String, CGFloat)]) -> String {
            entries.map { "\($0.0): \(number($0.1, decimals: 4))" }.joined(separator: ", ")
        }
        var lines = [
            "// \(MakeSiteBrand.header)",
            "// Logo units: the cap height is 100, the A's feet sit on the baseline at y = 0, and y grows downward.",
            "",
            "export const CHARCOAL = '\(hex(BrandMark.charcoal))';",
            "export const RED = '\(hex(BrandMark.red))';",
            "",
            "/** The tripod's numbers: the A's feet span, its legs' splay from vertical, and the thicknesses. */",
            "export const GEOMETRY = { \(object(geometry)) };",
            "",
            "/** SVG path data. The reels are rings, to fill even-odd. */",
            "export const PATHS = {",
        ]
        lines += paths.map { "  \($0.name): '\($0.data)'," }
        lines += [
            "  letters: '\(letters)',",
            "};",
            "",
            "/** The front reel's center and its ring's two radii. */",
            "export const FRONT_REEL = { \(object(reelNumbers)) };",
            "",
            "/** The mark and the letters, padded by \(number(MakeSiteBrand.padding, decimals: 2)). */",
            "export const LOGO_VIEWBOX = [\(viewBox(logoBox, separator: ", "))];",
            "/** The mark alone, in a square, padded by \(number(MakeSiteBrand.padding, decimals: 2)). */",
            "export const MARK_VIEWBOX = [\(viewBox(markBox, separator: ", "))];",
            "",
        ]
        return lines.joined(separator: "\n")
    }

    /// The sprite: ink paths fill with currentColor; the front reel has no fill of its own, so it takes the fill
    /// property from the <use> that shows it.
    func sprite() -> String {
        func symbol(_ id: String, box: CGRect, withLetters: Bool) -> String {
            var body = paths.map { path -> String in
                let fill = path.name == "frontReel" ? "" : " fill=\"currentColor\""
                let rule = path.evenOdd ? " fill-rule=\"evenodd\"" : ""
                return "<path\(fill)\(rule) d=\"\(path.data)\"/>"
            }
            if withLetters { body.append("<path fill=\"currentColor\" d=\"\(letters)\"/>") }
            return "<symbol id=\"\(id)\" viewBox=\"\(viewBox(box, separator: " "))\">\n\(body.joined(separator: "\n"))\n</symbol>"
        }
        return """
            <svg xmlns="http://www.w3.org/2000/svg">
            <!-- \(MakeSiteBrand.header) Pages set color for the ink and fill for the front reel. -->
            \(symbol("logo", box: logoBox, withLetters: true))
            \(symbol("mark", box: markBox, withLetters: false))
            </svg>

            """
    }

    /// The mark in white with the red front reel, on the app icon's body: inset 100/1024 and rounded 186/824 of its
    /// width, with the mark at 62% of its height, as scripts/make-icon.swift draws it.
    func favicon() -> String {
        let canvas: CGFloat = 64
        let inset = canvas * 100 / 1024
        let body = CGRect(x: inset, y: inset, width: canvas - 2 * inset, height: canvas - 2 * inset)
        let height = body.height * 0.62
        let width = height * BrandMark.bounds.width / BrandMark.bounds.height
        let fit = BrandMark.fitting(BrandMark.bounds, into: CGRect(x: body.midX - width / 2, y: body.midY - height / 2,
                                                                  width: width, height: height))
        let matrix = [fit.a, fit.b, fit.c, fit.d, fit.tx, fit.ty].map { number($0, decimals: 4) }.joined(separator: " ")
        let ink = paths.filter { $0.name != "frontReel" }.map { path in
            "<path\(path.evenOdd ? " fill-rule=\"evenodd\"" : "") d=\"\(path.data)\"/>"
        }
        return """
            <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
            <!-- \(MakeSiteBrand.header) -->
            <rect x="\(number(body.minX, decimals: 2))" y="\(number(body.minY, decimals: 2))" \
            width="\(number(body.width, decimals: 2))" height="\(number(body.height, decimals: 2))" \
            rx="\(number(body.width * 186 / 824, decimals: 2))" fill="\(hex(BrandMark.charcoal))"/>
            <g transform="matrix(\(matrix))">
            <g fill="#FFFFFF">
            \(ink.joined(separator: "\n"))
            </g>
            <path fill="\(hex(BrandMark.red))" fill-rule="evenodd" d="\(path("frontReel"))"/>
            </g>
            </svg>

            """
    }
}

/// Path data for a CGPath: absolute M, L, Q, C, and Z, with 2 decimals.
func pathData(_ path: CGPath) -> String {
    var parts: [String] = []
    path.applyWithBlock { element in
        let points = element.pointee.points
        func pairs(_ count: Int) -> String {
            (0..<count).map { "\(number(points[$0].x, decimals: 2)) \(number(points[$0].y, decimals: 2))" }
                .joined(separator: " ")
        }
        switch element.pointee.type {
        case .moveToPoint: parts.append("M\(pairs(1))")
        case .addLineToPoint: parts.append("L\(pairs(1))")
        case .addQuadCurveToPoint: parts.append("Q\(pairs(2))")
        case .addCurveToPoint: parts.append("C\(pairs(3))")
        case .closeSubpath: parts.append("Z")
        @unknown default: fatalError("an unknown path element")
        }
    }
    return parts.joined(separator: " ")
}

/// A number rounded to `decimals` places, without trailing zeros, and never "-0".
func number(_ value: CGFloat, decimals: Int) -> String {
    var text = String(format: "%.\(decimals)f", Double(value))
    if text.contains(".") {
        while text.hasSuffix("0") { text.removeLast() }
        if text.hasSuffix(".") { text.removeLast() }
    }
    return text == "-0" ? "0" : text
}

func viewBox(_ box: CGRect, separator: String) -> String {
    [box.minX, box.minY, box.width, box.height].map { number($0, decimals: 2) }.joined(separator: separator)
}

func hex(_ value: UInt32) -> String { String(format: "#%06X", value) }
