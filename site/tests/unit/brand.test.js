// The brand files are generated from the app's BrandMark.swift and Wordmark.swift (make site-brand). These check what
// they hold; make site-brand-check checks that they're up to date.
import { before, test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const assets = new URL('../../assets/', import.meta.url);
let brand, source;

before(async () => {
  source = await readFile(new URL('brand.js', assets), 'utf8');
  brand = await import(new URL('brand.js', assets));
});

/** The points of path data made of M, L, and Z. */
function polygon(d) {
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+/g);
  const points = [];
  for (let i = 0; i < tokens.length;) {
    if (tokens[i] === 'M' || tokens[i] === 'L') {
      points.push([Number(tokens[i + 1]), Number(tokens[i + 2])]);
      i += 3;
    } else if (tokens[i] === 'Z') {
      i += 1;
    } else {
      throw new Error(`${tokens[i]} in a polygon: ${d}`);
    }
  }
  return points;
}

function assertNear(actual, expected, tolerance, message) {
  assert.ok(Math.abs(actual - expected) <= tolerance, `${message}: ${actual} isn't within ${tolerance} of ${expected}`);
}

function assertPoints(actual, expected, message) {
  assert.equal(actual.length, expected.length, message);
  actual.forEach(([x, y], i) => {
    assertNear(x, expected[i][0], 0.01, `${message}, point ${i} x`);
    assertNear(y, expected[i][1], 0.01, `${message}, point ${i} y`);
  });
}

/** A PNG's size, from its IHDR chunk. */
async function pngSize(name) {
  const bytes = await readFile(new URL(name, assets));
  assert.equal(bytes.toString('latin1', 12, 16), 'IHDR', name);
  return [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
}

test('brand.js says it is generated, on its first line', () => {
  assert.equal(source.split('\n')[0],
    "// Generated by scripts/make-site-brand.swift from BrandMark.swift and Wordmark.swift. Don't edit: run make site-brand.");
});

test('the colors are the brand charcoal and the click-marker red', () => {
  assert.equal(brand.CHARCOAL, '#1C1C1E');
  assert.equal(brand.RED, '#FF3B30');
});

test("GEOMETRY holds the tripod's numbers from BrandMark", () => {
  assert.deepEqual(brand.GEOMETRY, {
    footSpan: 121, splayDegrees: 26, stem: 20.71, legThickness: 19.6745, braceThickness: 17.6035, legTop: -112,
    crossbarY: -38,
  });
});

test('the left leg and the brace are the polygons BrandMark draws', () => {
  assertPoints(polygon(brand.PATHS.leftLeg), [[0, 0], [21.89, 0], [76.52, -112], [54.63, -112]], 'the left leg');
  const brace = polygon(brand.PATHS.brace);
  assert.equal(brace.length, 4);
  const xs = brace.map(([x]) => x), ys = brace.map(([, y]) => y);
  assertNear(Math.min(...xs), 29.48, 0.01, 'brace left');
  assertNear(Math.max(...xs), 91.52, 0.01, 'brace right');
  assertNear(Math.min(...ys), -46.8, 0.01, 'brace top');
  assertNear(Math.max(...ys), -29.2, 0.01, 'brace bottom');
  for (const [x, y] of brace) {
    assert.ok([Math.min(...xs), Math.max(...xs)].includes(x) && [Math.min(...ys), Math.max(...ys)].includes(y),
      'the brace is a rectangle');
  }
});

test('every path has 2 decimals at most, and no -0', () => {
  for (const [name, d] of Object.entries(brand.PATHS)) {
    assert.doesNotMatch(d, /\d\.\d{3}/, name);
    assert.doesNotMatch(d, /-0(?![.\d])/, name);
    assert.doesNotMatch(d, /\.\d*0(?!\d)/, `${name} has no trailing zeros`);
  }
});

test('the letters are the wordmark, with its whitespace collapsed', () => {
  const letters = brand.PATHS.letters;
  assert.ok(letters.startsWith('M169.45 -40'), letters.slice(0, 20));
  assert.ok(letters.endsWith('Z'));
  assert.doesNotMatch(letters, /\s\s|\n/);
});

test('the front reel, and the view boxes', () => {
  const reel = brand.FRONT_REEL;
  assertNear(reel.cx, 93.17, 0.01, 'cx');
  assertNear(reel.cy, -198.85, 0.01, 'cy');
  assertNear(reel.outer, 27.83, 0.01, 'outer');
  assertNear(reel.inner, 12.705, 0.01, 'inner');
  assert.deepEqual(brand.LOGO_VIEWBOX, [-6, -232.68, 644.06, 240.11]);
  const [x, y, width, height] = brand.MARK_VIEWBOX;
  assert.equal(width, height, 'the mark view box is square');
  assert.ok(x < 0 && x + width > 151.25 && y < -226.68 && y + height > 0, 'the mark fits inside it');
});

test('brand.svg holds both symbols; ink takes currentColor, and the front reel takes the fill from <use>', async () => {
  const svg = await readFile(new URL('img/brand.svg', assets), 'utf8');
  const symbol = id => svg.match(new RegExp(`<symbol id="${id}" viewBox="([^"]+)">([\\s\\S]*?)</symbol>`));
  const logo = symbol('logo'), mark = symbol('mark');
  assert.ok(logo && mark, 'both symbols');
  assert.equal(logo[1], brand.LOGO_VIEWBOX.join(' '));
  assert.equal(mark[1], brand.MARK_VIEWBOX.join(' '));
  for (const [, , body] of [logo, mark]) {
    const paths = body.match(/<path [^>]*\/>/g);
    const reel = paths.find(path => path.includes(`d="${brand.PATHS.frontReel}"`));
    assert.ok(reel, 'the front reel is there');
    assert.doesNotMatch(reel, /\sfill="/, 'the front reel has no fill of its own');
    assert.match(reel, /fill-rule="evenodd"/);
    for (const path of paths.filter(path => path !== reel)) assert.match(path, /\sfill="currentColor"/);
    assert.match(paths.find(path => path.includes(`d="${brand.PATHS.backReel}"`)), /fill-rule="evenodd"/);
  }
  assert.ok(logo[2].includes(brand.PATHS.letters), 'the logo has the letters');
  assert.ok(!mark[2].includes(brand.PATHS.letters), "the mark doesn't");
});

test('favicon.svg is the mark on a charcoal rounded square, 64 units wide', async () => {
  const svg = await readFile(new URL('img/favicon.svg', assets), 'utf8');
  assert.match(svg, /viewBox="0 0 64 64"/);
  assert.match(svg, /<rect [^>]*fill="#1C1C1E"/);
  assert.ok(svg.includes(brand.PATHS.frontReel) && svg.includes('fill="#FF3B30"'), 'the red front reel');
});

test('the PNG icons are 32 and 180 px square', async () => {
  assert.deepEqual(await pngSize('img/favicon-32.png'), [32, 32]);
  assert.deepEqual(await pngSize('img/apple-touch-icon.png'), [180, 180]);
});
